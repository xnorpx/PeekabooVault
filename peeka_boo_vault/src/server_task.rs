//! Central ServerTask event loop for coordinating all PeekabooVault operations.
//!
//! This module implements a message-passing architecture that eliminates complex
//! Arc<Mutex<T>> patterns in favor of a single event loop that owns all mutable state.
//!
//! ## Architecture
//!
//! All coordination flows through `ServerMessage` enum sent to the ServerTask's channel.
//! The ServerTask owns:
//! - Camera registry
//! - RTSP client handles
//! - Recorder handles
//! - WebRTC session states
//! - Replay coordinator states
//!
//! ## Benefits
//!
//! - Single source of truth (no race conditions)
//! - Clear message flow (all coordination explicit)
//! - Easy to test (send messages, observe state)
//! - Predictable ordering (sequential message processing)
//! - Simple error handling (failures contained to handlers)

