/// Type alias for camera IDs
pub type CameraId = Uuid;

/// Type alias for stream types (e.g., "main", "sub")
pub type StreamType = String;

/// Type alias for session IDs
pub type SessionId = Uuid;

/// All messages that flow through the ServerTask event loop.
///
/// Messages are categorized by source:
/// - HTTP API (with oneshot channels for responses)
/// - RTSP Client (frame data and connection events)
/// - WebRTC Sessions (ICE, data channel commands)
/// - Recorder (segment completion, errors)
/// - Internal (shutdown)
#[derive(Debug)]
pub enum ServerMessage {
    // === HTTP API Messages (queries with oneshot response) ===
    /// Add a new camera to the system
    AddCamera {
        request: AddCameraRequest,
        respond_to: oneshot::Sender<anyhow::Result<Camera>>,
    },

    /// List all cameras
    ListCameras {
        respond_to: oneshot::Sender<Vec<Camera>>,
    },

    /// Get a specific camera by ID
    GetCamera {
        camera_id: CameraId,
        respond_to: oneshot::Sender<Option<Camera>>,
    },

    /// Delete a camera
    DeleteCamera {
        camera_id: CameraId,
        respond_to: oneshot::Sender<Option<Camera>>,
    },

    /// Set credentials for a camera
    SetCredentials {
        camera_id: CameraId,
        credentials: CameraCredentials,
        respond_to: oneshot::Sender<anyhow::Result<()>>,
    },

    /// List discovered devices
    ListDiscoveredDevices {
        respond_to: oneshot::Sender<Vec<DiscoveredDevice>>,
    },

    // === HTTP API Messages (commands, fire-and-forget) ===
    /// Start recording for a camera stream
    StartRecording {
        camera_id: CameraId,
        stream_type: StreamType,
    },

    /// Stop recording for a camera stream
    StopRecording {
        camera_id: CameraId,
        stream_type: StreamType,
    },

    /// Start RTSP client for a camera stream
    StartRtspClient {
        camera_id: CameraId,
        stream_type: StreamType,
        rtsp_url: String,
    },

    /// Stop RTSP client for a camera stream
    StopRtspClient {
        camera_id: CameraId,
        stream_type: StreamType,
    },

    // === RTSP Client Messages ===
    /// Video frame received from RTSP stream
    RtspFrame {
        camera_id: CameraId,
        stream_type: StreamType,
        frame: VideoFrame,
    },

    /// RTSP connection established
    RtspConnected {
        camera_id: CameraId,
        stream_type: StreamType,
        codec_info: CodecInfo,
    },

    /// RTSP connection lost
    RtspDisconnected {
        camera_id: CameraId,
        stream_type: StreamType,
        error: Option<String>,
    },

    // === WebRTC Session Messages ===
    /// ICE candidate generated by WebRTC session
    WebRtcIceCandidate {
        session_id: SessionId,
        candidate: String, // TODO: Use proper ICE candidate type
    },

    /// Data channel message received
    WebRtcDataChannelMessage {
        session_id: SessionId,
        message: DataChannelCommand,
    },

    /// WebRTC session closed
    WebRtcSessionClosed {
        session_id: SessionId,
    },

    // === Recorder Messages ===
    /// Recording segment completed and written to disk
    RecordingSegmentComplete {
        camera_id: CameraId,
        stream_type: StreamType,
        segment_info: SegmentInfo,
    },

    /// Recording error occurred
    RecordingError {
        camera_id: CameraId,
        stream_type: StreamType,
        error: String,
    },

    // === Internal Messages ===
    /// Shutdown the server task
    Shutdown,
}

